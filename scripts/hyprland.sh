#!/usr/bin/env bash
# Optional Hyprland integration (keybinds + autostart). Never runs unless you ask:
#   ./scripts/hyprland.sh install    add binds/autostart (backs up hyprland.conf first)
#   ./scripts/hyprland.sh remove     undo exactly that
#   ./scripts/hyprland.sh show       print the snippet without installing
#
# The avatar itself needs NO window rules: it is a layer-shell surface (namespace
# "wednesday-avatar"/"wednesday-panel"), so it floats above windows without touching your config.
set -euo pipefail
HERE="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
HYPR="${XDG_CONFIG_HOME:-$HOME/.config}/hypr"
MAIN="$HYPR/hyprland.conf"
SNIP="$HYPR/wednesday.conf"
LINE="source = $SNIP   # wednesday"

snippet() {
cat <<EOF
# Wednesday — generated by $HERE/scripts/hyprland.sh (safe to delete; run 'remove' to unhook)
exec-once = $HERE/wednesday start
bind = SUPER ALT, W, exec, $HERE/wednesday panel     # open/close chat
bind = SUPER ALT, H, exec, $HERE/wednesday toggle    # show/hide avatar
bind = SUPER ALT, T, exec, $HERE/wednesday talk      # push-to-talk (press again to send)
bind = SUPER ALT, X, exec, $HERE/wednesday halt      # emergency stop
# Optional: subtle blur behind the chat panel
layerrule = blur, wednesday-panel
layerrule = ignorezero, wednesday-panel
EOF
}

conflicts() {
  # modmask 72 = SUPER(64) + ALT(8)
  hyprctl binds -j 2>/dev/null | python3 -c '
import json, sys
taken = {b["key"].upper() for b in json.load(sys.stdin) if b["modmask"] == 72}
print(" ".join(k for k in ("W", "H", "T", "X") if k in taken))'
}

case "${1:-show}" in
  show) snippet ;;
  install)
    [[ -f "$MAIN" ]] || { echo "No $MAIN found — is this Hyprland?"; exit 1; }
    if grep -qF "# wednesday" "$MAIN"; then echo "Already installed."; exit 0; fi
    c=$(conflicts || true)
    if [[ -n "$c" ]]; then echo "SUPER+ALT+{$c} already bound in your config — edit $SNIP keys first. Nothing changed."; exit 1; fi
    cp "$MAIN" "$MAIN.bak-wednesday-$(date +%Y%m%d-%H%M%S)"
    snippet > "$SNIP"
    printf '\n%s\n' "$LINE" >> "$MAIN"
    hyprctl reload >/dev/null 2>&1 || true
    echo "Installed: $SNIP (backup of hyprland.conf saved next to it)."
    echo "Keys: SUPER+ALT+W chat · SUPER+ALT+H hide/show · SUPER+ALT+T talk · SUPER+ALT+X emergency stop"
    ;;
  remove)
    if [[ -f "$MAIN" ]] && grep -qF "# wednesday" "$MAIN"; then
      cp "$MAIN" "$MAIN.bak-wednesday-remove-$(date +%Y%m%d-%H%M%S)"
      grep -vF "$LINE" "$MAIN" > "$MAIN.tmp" && mv "$MAIN.tmp" "$MAIN"
      rm -f "$SNIP"
      hyprctl reload >/dev/null 2>&1 || true
      echo "Removed Wednesday's Hyprland hook."
    fi
    ;;
  *) echo "usage: $0 show|install|remove"; exit 2 ;;
esac
